public class conditional {
    public static void main(String[] args){
        int x=4;
        switch (x){
            case 1:
                System.out.println("Value is 1.");
                break;
            case 2:
                System.out.println("Value is 2.");
                break;
            case 3:
                System.out.println("Value is 3.");      
                break;
            default:
                System.out.println("Value is not 1, 2, or 3.");

        }
        

}    
}
