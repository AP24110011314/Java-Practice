public class variables {
    public static void main(String[] args) {
        // Declare a variable
        int number = 10;
        byte byteNumber = 100;
        short shortNumber = 30000;
        long longNumber = 100000L;

        double decimalNumber = 5.5;
        float floatNumber = 3.14f;
        boolean isTrue = true;
        char letter = 'A';
        String text = "Hello, World!";

        // Print the value of the variable
        System.out.println("The value of the variable is: " + number);
        System.out.println("The value of the decimal variable is: " + decimalNumber);
        System.out.println("The value of the float variable is: " + floatNumber);
        System.out.println("The value of the boolean variable is: " + isTrue);
        System.out.println("The value of the char variable is: " + letter);
        System.out.println("The value of the string variable is: " + text);
        System.out.println("The value of the byte variable is: " + byteNumber);
        System.out.println("The value of the short variable is: " + shortNumber);
        System.out.println("The value of the long variable is: " + longNumber);
    }
}